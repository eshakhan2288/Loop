#include <iostream>
using namespace std;

int main() {
    // 1 se 10 tak
    for (int i = 1; i <= 10; i++) {
        cout << i << " ";
    }
    cout << endl;

    // 10 se 1 tak
    for (int i = 10; i >= 1; i--) {
        cout << i << " ";
    }
    cout << endl;

    return 0;
}
